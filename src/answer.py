def build_supplement_prompt(question: str, answered: str, history_text: str) -> tuple[str, str]:
    """補足の係に渡す、指示文（毎回同じ）と、質問の側（毎回変わる）を作る。資料の本文は渡さない。"""
    user = (
        f"<history>\n{history_text}\n</history>\n\n"
        f"<question>\n{question}\n</question>\n\n"
        f"<answered>\n{answered.strip() or '（ありません）'}\n</answered>"
    )
    return SUPPLEMENT_RULES, user


def describe_materials(chunks: list[Chunk]) -> str:
    if not chunks:
        return "（ありません）"
    return "\n\n".join(f"【{chunk.label}｜{chunk.title}】\n{chunk.text}" for chunk in chunks)


def describe_terms(terms: list[Term]) -> str:
    if not terms:
        return "（ありません）"
    return "\n".join(f"・{term.term}：{term.description}" for term in terms)


def build_answer_prompt(
    question: str, chunks: list[Chunk], terms: list[Term], screen_text: str, history_text: str
) -> tuple[str, str]:
    """回答でAIに渡す、指示文（毎回同じ）と、資料と質問の側（毎回変わる）を作る。"""
    user = (
        f"<materials>\n{describe_materials(chunks)}\n</materials>\n\n"
        f"<glossary>\n{describe_terms(terms)}\n</glossary>\n\n"
        f"<screen>\n{screen_text}\n</screen>\n\n"
        f"<history>\n{history_text}\n</history>\n\n"
        f"<question>\n{question}\n</question>"
    )
    return ANSWER_RULES, user
